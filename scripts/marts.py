sys.stdout.reconfigure(encoding='utf-8')

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАПКА = os.path.join(КОРЕНЬ, 'analytics')
АДРЕСА = [
    'https://d5dlpkp30bicbqp0edul.7qsg961h.apigw.yandexcloud.net',
    'https://mk-bot.more-krasok-bot.workers.dev',
]
ДНИ = ['понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота', 'воскресенье']
МЕСЯЦЫ = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
          'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря']


def ключ():
    k = os.environ.get('MK_KEY')
    if k:
        return k.strip()
    путь = os.path.join(КОРЕНЬ, 'bot', '.planer-key')
    if os.path.exists(путь):
        return io.open(путь, encoding='utf-8').read().strip()
    raise SystemExit('Нет ключа. Положите его в bot/.planer-key или в переменную MK_KEY.')


def выгрузка(k):
    """Сначала российский шлюз, потом прямой адрес: шлюз бывает недоступен."""
    последняя = None
    for адрес in АДРЕСА:
        try:
            # без своего названия Cloudflare отвечает отказом, принимая нас за робота
            запрос = urllib.request.Request(
                адрес + '/export?key=' + k,
                headers={'User-Agent': 'more-krasok-analytics'},
            )
            with urllib.request.urlopen(запрос, timeout=15) as r:
                return json.loads(r.read().decode('utf-8'))['записи']
        except Exception as e:  # noqa: BLE001 — какой именно сбой, неважно: пробуем следующий
            последняя = e
    raise SystemExit('Не получилось забрать выгрузку: %s' % последняя)


# ---- справочник услуг: длительность и цена ----
ПРАЙС = {}
_прайс = json.load(io.open(os.path.join(КОРЕНЬ, 'prices.json'), encoding='utf-8'))
for _кат in _прайс['categories']:
    for _у in _кат['services']:
        ПРАЙС[_у['n']] = {'цена': _у['p'], 'мин': _у['m'], 'группа': _кат['name']}

# Названия до смены прайса: в старых записях они остались, иначе треть
# выручки потерялась бы как «услуга неизвестна».
СТАРЫЕ = {
    'Маникюр': 'Маникюр с покрытием гель-лак',
    'Педикюр': 'Педикюр комбинированный (полная обработка)',
    'Окрашивание': 'Окрашивание / тонирование в один тон до 45 см',
    'Химзавивка': 'Химическая завивка до 15 см',
    'Женская стрижка': 'Стрижка женская',
    'Мужская стрижка': 'Стрижка мужская',
    'Детская стрижка': 'Стрижка детская',
    'Брови': 'Коррекция бровей',
}


def услуга(имя):
    return имя if имя in ПРАЙС else СТАРЫЕ.get(имя, имя)


def вилсон(k, n):
    """Доля и её интервал по Вилсону. На наших объёмах интервал широкий,
    и показывать его обязательно: без него доля выглядит точнее, чем есть."""
    if not n:
        return (None, None, None)
    z = 1.959963985
    p = k / n
    зн = 1 + z * z / n
    центр = (p + z * z / (2 * n)) / зн
    разброс = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / зн
    return (p, max(0.0, центр - разброс), min(1.0, центр + разброс))


def подготовить(строки):
    out = []
    for b in строки:
        д = date.fromisoformat(b['day'])
        создана = datetime.fromisoformat(b['created_at'].replace('Z', '+00:00'))
        имя = услуга(b['service'])
        сп = ПРАЙС.get(имя, {})
        out.append({
            'id': b['id'],
            'день': b['day'],
            'создана': создана.date().isoformat(),
            'горизонт_дней': (д - создана.date()).days,
            'начало': b['start_min'],
            'минут': (b['end_min'] or 0) - (b['start_min'] or 0),
            'услуга': имя,
            'группа': сп.get('группа', 'прочее'),
            'цена': сп.get('цена'),
            'канал': b['client_kind'] or 'сайт_или_мастер',
            'статус': b['status'],
            'напомнили': b['reminded_day'],
            'явка': '' if b['attended'] is None else ('пришёл' if b['attended'] else 'не пришёл'),
            'день_недели': ДНИ[д.weekday()],
            'месяц': b['day'][:7],
        })
    return out


def csv_файл(имя, поля, строки):
    путь = os.path.join(ПАПКА, имя)
    with io.open(путь, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=поля, delimiter=';')
        w.writeheader()
        for r in строки:
            w.writerow({k: r.get(k, '') for k in поля})
    return путь


# ---- рисование: простые столбики в SVG, без внешних библиотек ----
def столбики(данные, подпись='', высота=170, цвет='#d4a5a5'):
    if not данные:
        return '<p class="пусто">нет данных</p>'
    макс = max(v for _, v in данные) or 1
    ш = max(26, min(64, int(680 / len(данные))))
    полная = ш * len(данные)
    куски = []
    строк_подписи = max(len(разбить(имя)) for имя, _ in данные)
    низ = 6 + 11 * строк_подписи
    куски = []
    for i, (имя, v) in enumerate(данные):
        h = int((v / макс) * (высота - низ - 16))
        x = i * ш
        строки_имени = разбить(имя)
        текст = ''.join(
            '<text x="%d" y="%d" class="ось">%s</text>' % (x + ш / 2, высота - низ + 12 + 11 * j, кусок)
            for j, кусок in enumerate(строки_имени))
        куски.append(
            '<rect x="%d" y="%d" width="%d" height="%d" rx="4" fill="%s"/>'
            '<text x="%d" y="%d" class="зн">%s</text>%s'
            % (x + 4, высота - низ - h, ш - 8, max(h, 2), цвет,
               x + ш / 2, высота - низ - h - 4, ('%g' % round(v, 1)), текст))
    return ('<svg viewBox="0 0 %d %d" class="гр" role="img" aria-label="%s">%s</svg>'
            % (полная, высота + 11 * (строк_подписи - 1), подпись, ''.join(куски)))


def разбить(имя, ширина=13, строк=2):
    """Подпись в две строки: «Стрижка женская» и «Стрижка детская» одним
    словом не различить, а целиком они не помещаются."""
    слова, вышло, текущая = str(имя).split(), [], ''
    for сл in слова:
        проба = (текущая + ' ' + сл).strip()
        if len(проба) <= ширина or not текущая:
            текущая = проба
        else:
            вышло.append(текущая)
            текущая = сл
    вышло.append(текущая)
    вышло = вышло[:строк]
    if len(вышло) == строк and len(' '.join(слова)) > sum(len(x) for x in вышло) + строк - 1:
        вышло[-1] = вышло[-1][:ширина - 1] + '…'
    return вышло


def плитка(заголовок, значение, пояснение=''):
    return ('<div class="плитка"><p class="подпись">%s</p><p class="число">%s</p>'
            '<p class="мелко">%s</p></div>' % (заголовок, значение, пояснение))


def main():
    os.makedirs(ПАПКА, exist_ok=True)
    строки = подготовить(выгрузка(ключ()))
    сегодня = date.today().isoformat()
    живые = [r for r in строки if r['статус'] != 'cancelled']
    прошедшие = [r for r in живые if r['день'] < сегодня]

    # ---- витрины ----
    поля = ['id', 'день', 'создана', 'горизонт_дней', 'начало', 'минут', 'услуга',
            'группа', 'цена', 'канал', 'статус', 'напомнили', 'явка', 'день_недели', 'месяц']
    csv_файл('zapisi.csv', поля, строки)

    по_мес = defaultdict(lambda: Counter())
    for r in строки:
        c = по_мес[r['месяц']]
        c['всего'] += 1
        c['отменено'] += r['статус'] == 'cancelled'
        c['пришли'] += r['явка'] == 'пришёл'
        c['не_пришли'] += r['явка'] == 'не пришёл'
        if r['статус'] != 'cancelled':
            c['часов'] += r['минут'] / 60
            c['выручка_план'] += r['цена'] or 0
    месяцы = sorted(по_мес)
    csv_файл('po_mesyacam.csv',
             ['месяц', 'всего', 'отменено', 'пришли', 'не_пришли', 'часов', 'выручка_план'],
             [dict({'месяц': m}, **{k: round(v, 1) for k, v in по_мес[m].items()}) for m in месяцы])

    по_дням = Counter(r['день'] for r in живые)
    создано = Counter(r['создана'] for r in строки)
    csv_файл('po_dnyam.csv', ['дата', 'записей_на_день', 'записались_в_этот_день'],
             [{'дата': d, 'записей_на_день': по_дням.get(d, 0), 'записались_в_этот_день': создано.get(d, 0)}
              for d in sorted(set(list(по_дням) + list(создано)))])

    загрузка = Counter()
    for r in живые:
        загрузка[(r['день_недели'], r['начало'] // 60)] += r['минут'] / 60
    csv_файл('zagruzka.csv', ['день_недели', 'час', 'часов_занято'],
             [{'день_недели': д, 'час': ч, 'часов_занято': round(v, 2)}
              for (д, ч), v in sorted(загрузка.items(), key=lambda x: (ДНИ.index(x[0][0]), x[0][1]))])

    усл = defaultdict(lambda: Counter())
    for r in живые:
        c = усл[r['услуга']]
        c['записей'] += 1
        c['часов'] += r['минут'] / 60
        c['выручка_план'] += r['цена'] or 0
    csv_файл('uslugi.csv', ['услуга', 'группа', 'записей', 'часов', 'выручка_план'],
             [{'услуга': u, 'группа': ПРАЙС.get(u, {}).get('группа', 'прочее'),
               'записей': c['записей'], 'часов': round(c['часов'], 1),
               'выручка_план': int(c['выручка_план'])}
              for u, c in sorted(усл.items(), key=lambda x: -x[1]['записей'])])

    корзины = [(0, 0, 'в тот же день'), (1, 1, 'за день'), (2, 3, '2–3 дня'),
               (4, 7, '4–7 дней'), (8, 14, '1–2 недели'), (15, 30, '2–4 недели'), (31, 9999, 'дальше')]
    гор = []
    for lo, hi, имя in корзины:
        n = sum(1 for r in строки if lo <= r['горизонт_дней'] <= hi)
        гор.append({'горизонт': имя, 'записей': n})
    csv_файл('gorizont.csv', ['горизонт', 'записей'], гор)

    # ---- числа для дашборда ----
    отмен = sum(1 for r in строки if r['статус'] == 'cancelled')
    доля_отмен, о_низ, о_верх = вилсон(отмен, len(строки))
    отмечено = [r for r in прошедшие if r['явка']]
    неявок = sum(1 for r in отмечено if r['явка'] == 'не пришёл')
    доля_неявок, н_низ, н_верх = вилсон(неявок, len(отмечено))
    с_чатом = sum(1 for r in строки if r['канал'] in ('tg', 'max'))
    дней_всего = max(1, (date.fromisoformat(max(r['создана'] for r in строки))
                         - date.fromisoformat(min(r['создана'] for r in строки))).days)
    в_месяц = len(строки) / дней_всего * 30.4
    часы_впустую = sum(r['минут'] for r in отмечено if r['явка'] == 'не пришёл') / 60
    деньги_впустую = sum(r['цена'] or 0 for r in отмечено if r['явка'] == 'не пришёл')

    def проц(x):
        return '—' if x is None else '%.0f%%' % (x * 100)

    неявки_блок = (
        плитка('Неявки', проц(доля_неявок),
               'отмечено %d записей из %d прошедших · интервал %s–%s'
               % (len(отмечено), len(прошедшие), проц(н_низ), проц(н_верх)))
        if отмечено else
        плитка('Неявки', 'пока нечего считать',
               'отметок «пришла / не пришла» ещё нет — ставьте их в планере'))

    шапка = ''.join([
        плитка('Записей всего', str(len(строки)), 'с %s' % min(r['создана'] for r in строки)),
        плитка('В месяц', '%.0f' % в_месяц, 'это потолок выборки для любых расчётов'),
        плитка('Отмены', проц(доля_отмен), 'интервал %s–%s' % (проц(о_низ), проц(о_верх))),
        неявки_блок,
        плитка('Записались через бота', '%d из %d' % (с_чатом, len(строки)),
               'только им может дойти напоминание'),
        плитка('Потеряно на неявках', '%.1f ч · %d ₽' % (часы_впустую, деньги_впустую),
               'по отмеченным записям' if отмечено else 'появится после отметок'),
    ])

    мес_подпись = lambda m: МЕСЯЦЫ[int(m[5:]) - 1][:3] + ' ' + m[2:4]  # noqa: E731
    график_месяцы = столбики([(мес_подпись(m), по_мес[m]['всего']) for m in месяцы], 'Записи по месяцам')
    график_выручка = столбики([(мес_подпись(m), round(по_мес[m]['выручка_план'] / 1000, 1)) for m in месяцы],
                              'Выручка по месяцам, тыс. ₽', цвет='#7f9f80')
    график_дни = столбики([(д[:2], round(sum(v for (дн, _), v in загрузка.items() if дн == д), 1)) for д in ДНИ],
                          'Занятые часы по дням недели', цвет='#8a9fd4')
    часы = sorted({ч for _, ч in загрузка})
    график_часы = столбики([('%d' % ч, round(sum(v for (_, c), v in загрузка.items() if c == ч), 1)) for ч in часы],
                           'Занятые часы по времени суток', цвет='#c9a227')
    график_услуги = столбики([(u, c['записей'])
                              for u, c in sorted(усл.items(), key=lambda x: -x[1]['записей'])[:8]],
                             'Топ услуг', высота=190)
    график_горизонт = столбики([(г['горизонт'], г['записей']) for г in гор],
                               'За сколько записываются', цвет='#b48ead')

    html = ШАБЛОН
    for ключик, значение in [
        ('@дата@', datetime.now().strftime('%d.%m.%Y %H:%M')),
        ('@шапка@', шапка),
        ('@месяцы@', график_месяцы),
        ('@выручка@', график_выручка),
        ('@дни@', график_дни),
        ('@часы@', график_часы),
        ('@услуги@', график_услуги),
        ('@горизонт@', график_горизонт),
        ('@строк@', str(len(строки))),
    ]:
        html = html.replace(ключик, значение)
    путь = os.path.join(ПАПКА, 'dashboard.html')
    io.open(путь, 'w', encoding='utf-8').write(html)

    print('Записей: %d, живых: %d, прошедших: %d' % (len(строки), len(живые), len(прошедшие)))
    print('Отмены: %s (%d из %d)' % (проц(доля_отмен), отмен, len(строки)))
    print('Явка отмечена у %d записей' % len(отмечено))
    print('Витрины и дашборд: %s' % ПАПКА)


