"""Витрины и дашборд по записям студии.

    python scripts/marts.py

Берёт построчную выгрузку с сервера бота (/export — без имён и телефонов,
их в этой базе нет вовсе), считает витрины и складывает их в analytics/:

    zapisi.csv       очищенные записи с производными полями
    po_mesyacam.csv  записи, отмены, неявки по месяцам
    po_dnyam.csv     по датам: сколько создано и сколько назначено
    zagruzka.csv     занятые часы по дням недели и времени суток
    uslugi.csv       что заказывают и сколько это стоит
    gorizont.csv     за сколько дней записываются
    dashboard.html   всё то же картинками, открывается двойным щелчком

Ключ берётся из переменной окружения MK_KEY или из файла bot/.planer-key —
в репозиторий он не попадает. Папка analytics/ тоже не коммитится: это
данные мастера, а не код.
"""
