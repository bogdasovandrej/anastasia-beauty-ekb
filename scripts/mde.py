import math, sys
sys.stdout.reconfigure(encoding='utf-8')

def z(p):  # обратная функция нормального распределения, приближение Акклама
    a=[-3.969683028665376e+01,2.209460984245205e+02,-2.759285104469687e+02,1.383577518672690e+02,-3.066479806614716e+01,2.506628277459239e+00]
    b=[-5.447609879822406e+01,1.615858368580409e+02,-1.556989798598866e+02,6.680131188771972e+01,-1.328068155288572e+01]
    c=[-7.784894002430293e-03,-3.223964580411365e-01,-2.400758277161838e+00,-2.549732539343734e+00,4.374664141464968e+00,2.938163982698783e+00]
    d=[7.784695709041462e-03,3.224671290700398e-01,2.445134137142996e+00,3.754408661907416e+00]
    pl=0.02425
    if p<pl:
        q=math.sqrt(-2*math.log(p))
        return (((((c[0]*q+c[1])*q+c[2])*q+c[3])*q+c[4])*q+c[5])/((((d[0]*q+d[1])*q+d[2])*q+d[3])*q+1)
    if p>1-pl:
        return -z(1-p)
    q=p-0.5; r=q*q
    return (((((a[0]*r+a[1])*r+a[2])*r+a[3])*r+a[4])*r+a[5])*q/(((((b[0]*r+b[1])*r+b[2])*r+b[3])*r+b[4])*r+1)

Z_A = z(1-0.05/2)   # 1.96
Z_B = z(0.80)       # 0.84

def mde(p, n_arm):
    """Минимальный обнаружимый сдвиг доли при двух равных группах."""
    lo, hi = 0.0, min(p, 1-p)
    for _ in range(100):
        d = (lo+hi)/2
        p2 = p - d
        se = math.sqrt(p*(1-p)/n_arm + p2*(1-p2)/n_arm)
        if (Z_A+Z_B)*se <= d: hi = d
        else: lo = d
    return hi

def n_needed(p, effect):
    p2 = p - effect
    pbar = (p+p2)/2
    n = ((Z_A*math.sqrt(2*pbar*(1-pbar)) + Z_B*math.sqrt(p*(1-p)+p2*(1-p2)))**2)/(effect**2)
    return math.ceil(n)

ПОТОК = 75          # записей в месяц (161 запись за ~2,1 месяца)
С_ЧАТОМ_ДОЛЯ = 5/161
print('Поток: %d записей в месяц, из них с чатом в мессенджере: %.1f%%' % (ПОТОК, С_ЧАТОМ_ДОЛЯ*100))
print()
print('MDE для доли неявок (α=0.05, мощность 80%, две равные группы):')
print('  недель | записей/группа | базовая неявка 10%% | 15%% | 20%%')
for нед in (4, 8, 12, 26, 52):
    n = ПОТОК*нед/4.345/2
    row = '  %6d | %14.0f |' % (нед, n)
    for p in (0.10, 0.15, 0.20):
        row += ' %17s' % ('%.1f п.п.' % (mde(p, n)*100))
    print(row)
print()
print('Сколько нужно записей в каждой группе, чтобы поймать реалистичный эффект')
print('(базовая неявка 15%):')
for eff in (0.02, 0.03, 0.05, 0.07, 0.10):
    n = n_needed(0.15, eff)
    print('  эффект %4.1f п.п. → %5d записей на группу = %5.1f месяца при %d записях/мес' % (eff*100, n, n*2/ПОТОК, ПОТОК))
